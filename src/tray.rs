use crate::popup::Popup;
use std::{
    sync::{
        atomic::{AtomicBool, Ordering},
        Arc,
    },
    thread,
    time::{Duration, Instant},
};

/// Ignore a tray click this soon after the popup closed. Pressing the tray
/// icon takes focus away first (which hides the popup), so without this the
/// same click would immediately open it again.
const REOPEN_GUARD: Duration = Duration::from_millis(500);

pub fn start(settings_url: String) -> Arc<AtomicBool> {
    let quit = Arc::new(AtomicBool::new(false));
    let thread_quit = Arc::clone(&quit);
    thread::Builder::new()
        .name("craftpulse-tray".to_string())
        .spawn(move || run_tray(settings_url, thread_quit))
        .expect("could not create tray thread");
    quit
}

fn run_tray(settings_url: String, quit: Arc<AtomicBool>) {
    use tao::{
        event::{Event, WindowEvent},
        event_loop::{ControlFlow, EventLoopBuilder, EventLoopWindowTarget},
    };
    use tray_icon::{
        menu::{Menu, MenuEvent, MenuItem, PredefinedMenuItem},
        Icon, MouseButton, MouseButtonState, Rect, TrayIconBuilder, TrayIconEvent,
    };

    // On Windows, tao refuses to create an event loop off the main thread
    // unless `with_any_thread(true)` is set. The tray runs on its own thread.
    #[allow(unused_mut)]
    let mut builder = EventLoopBuilder::new();
    #[cfg(windows)]
    {
        use tao::platform::windows::EventLoopBuilderExtWindows;
        builder.with_any_thread(true);
    }
    // Same on Linux (X11 and Wayland): the tray runs off the main thread.
    #[cfg(target_os = "linux")]
    {
        use tao::platform::unix::EventLoopBuilderExtUnix;
        builder.with_any_thread(true);
    }
    let event_loop = builder.build();

    let menu = Menu::new();
    let open_item = MenuItem::new("Open CraftPulse", true, None);
    let browser_item = MenuItem::new("Open in browser", true, None);
    let pause_hour_item = MenuItem::new("Pause sharing for 1 hour", true, None);
    let pause_item = MenuItem::new("Pause until I resume", true, None);
    let resume_item = MenuItem::new("Resume sharing", true, None);
    let quit_item = MenuItem::new("Quit", true, None);
    let _ = menu.append_items(&[
        &open_item,
        &browser_item,
        &PredefinedMenuItem::separator(),
        &pause_hour_item,
        &pause_item,
        &resume_item,
        &PredefinedMenuItem::separator(),
        &quit_item,
    ]);
    let pause_hour_id = pause_hour_item.id().clone();
    let pause_id = pause_item.id().clone();
    let resume_id = resume_item.id().clone();
    let open_id = open_item.id().clone();
    let browser_id = browser_item.id().clone();
    let quit_id = quit_item.id().clone();

    // 64x64 RGBA, generated by assets/make_icons.py.
    let icon = Icon::from_rgba(include_bytes!("../assets/tray.rgba").to_vec(), 64, 64)
        .expect("invalid tray icon image");
    // When Windows starts the app at login, the taskbar (Explorer) may not be
    // ready yet and creating the icon fails. Keep retrying for up to two
    // minutes instead of giving up, which left the app running with no icon.
    let started = Instant::now();
    let _tray = loop {
        let attempt = TrayIconBuilder::new()
            .with_menu(Box::new(menu.clone()))
            // Left-click opens the popup; right-click shows the menu.
            .with_menu_on_left_click(false)
            .with_tooltip("CraftPulse")
            .with_icon(icon.clone())
            .build();
        match attempt {
            Ok(tray) => break tray,
            Err(_) if started.elapsed() < Duration::from_secs(120) => {
                if quit.load(Ordering::Relaxed) {
                    return;
                }
                thread::sleep(Duration::from_secs(2));
            }
            Err(_) => {
                // No tray (for example GNOME without the AppIndicator extension):
                // open the settings page so the app is still reachable.
                let _ = open::that(&settings_url);
                return;
            }
        }
    };
    let menu_events = MenuEvent::receiver();
    let tray_events = TrayIconEvent::receiver();

    let browser_url = settings_url;
    let popup_url = format!("{browser_url}&popup=1");
    let mut popup: Option<Popup> = None;
    let mut last_hidden = Instant::now() - Duration::from_secs(5);

    // Opens the popup, creating it on first use. If it can't be created
    // (for example WebView2 is missing), open the settings in the browser.
    fn show_popup(
        popup: &mut Option<Popup>,
        target: &EventLoopWindowTarget<()>,
        popup_url: &str,
        browser_url: &str,
        anchor: Option<Rect>,
    ) {
        if popup.is_none() {
            *popup = Popup::new(target, popup_url);
        }
        match popup.as_mut() {
            Some(popup) => popup.show(anchor),
            None => {
                let _ = open::that(browser_url);
            }
        }
    }

    event_loop.run(move |event, target, control_flow| {
        *control_flow = ControlFlow::WaitUntil(Instant::now() + Duration::from_millis(50));
        if quit.load(Ordering::Relaxed) {
            *control_flow = ControlFlow::Exit;
            return;
        }

        // The popup closes with Alt+F4, or when you click on another window.
        let close_requested = matches!(
            &event,
            Event::WindowEvent {
                event: WindowEvent::CloseRequested,
                ..
            }
        );
        if let Some(popup) = popup.as_mut() {
            if popup.is_visible() && (close_requested || popup.lost_focus()) {
                popup.hide();
                last_hidden = Instant::now();
            }
        }

        while let Ok(event) = menu_events.try_recv() {
            if event.id == open_id {
                show_popup(&mut popup, target, &popup_url, &browser_url, None);
            } else if event.id == browser_id {
                let _ = open::that(&browser_url);
            } else if event.id == pause_hour_id {
                crate::pause::pause_for_minutes(60);
            } else if event.id == pause_id {
                crate::pause::pause_until_resumed();
            } else if event.id == resume_id {
                crate::pause::resume();
            } else if event.id == quit_id {
                quit.store(true, Ordering::Relaxed);
                *control_flow = ControlFlow::Exit;
            }
        }

        while let Ok(event) = tray_events.try_recv() {
            if let TrayIconEvent::Click {
                rect,
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                if popup.as_ref().is_some_and(|popup| popup.is_visible()) {
                    if let Some(popup) = popup.as_mut() {
                        popup.hide();
                        last_hidden = Instant::now();
                    }
                } else if last_hidden.elapsed() > REOPEN_GUARD {
                    show_popup(&mut popup, target, &popup_url, &browser_url, Some(rect));
                }
            }
        }
    });
}
